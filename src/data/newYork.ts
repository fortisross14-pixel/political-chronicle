import { deriveMedia, deriveOpinions, profile } from '../engine/demographics';
import type { Demo } from '../engine/demographics';
import type { IssueId, Office, Region, RegionType, UsState } from '../engine/types';

interface PlaceSpec {
  id: string;
  name: string;
  seatCity: string;
  type: RegionType;
  population: number;
  turnout: number;
  /** −1 Blue .. +1 Red: the place's voting history. */
  lean: number;
  demo: Demo;
  blurb: string;
  /** Local pulls on top of what the demographics say. */
  quirks?: Partial<Record<IssueId, number>>;
  /** Neighborhoods: the district they sit in. */
  parent?: string;
}

/** A district or neighborhood: opinions, salience and media all follow from lean, type and people. */
function place(p: PlaceSpec): Region {
  return {
    id: p.id,
    state: 'NY',
    name: p.name,
    seatCity: p.seatCity,
    type: p.type,
    population: p.population,
    turnout: p.turnout,
    partisanLean: p.lean,
    demo: p.demo,
    ...(p.parent ? { parent: p.parent } : {}),
    blurb: p.blurb,
    media: deriveMedia(p.type, p.demo),
    ...deriveOpinions(p.lean, p.type, p.demo, p.quirks),
  };
}

