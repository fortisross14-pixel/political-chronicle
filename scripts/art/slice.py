"""Slices art/grids/<id>.png (6 x 4 cells) into public/art/<cell id>.webp and rewrites
src/data/artManifest.ts with the ids that now have art.

Generators rarely draw a perfect grid, so the gutters are found, not assumed: near each expected
boundary we look for the column (or row) of pixels closest to the gutter colour.
Usage: python3 -I scripts/art/slice.py [grid id ...]   (no ids: every grid that has an image)
"""
import json
import sys
from pathlib import Path

from PIL import Image, ImageStat

ROOT = Path(__file__).resolve().parents[2]
COLS, ROWS = 6, 4
OUT = ROOT / "public" / "art"
SIZE = 384
GUTTER = (11, 20, 48)


def line_score(img, axis, pos):
    """Mean distance of a pixel line from the gutter colour (lower = more gutter-like)."""
    w, h = img.size
    box = (pos, 0, pos + 1, h) if axis == "x" else (0, pos, w, pos + 1)
    mean = ImageStat.Stat(img.crop(box)).mean
    return sum(abs(m - g) for m, g in zip(mean, GUTTER)) + sum(ImageStat.Stat(img.crop(box)).stddev) * 0.5


def boundaries(img, axis, n):
    """n + 1 cut lines along an axis, each snapped to the most gutter-like line nearby."""
    length = img.size[0] if axis == "x" else img.size[1]
    step = length / n
    window = int(step * 0.08)
    cuts = []
    for k in range(n + 1):
        guess = int(round(k * step))
        lo, hi = max(0, guess - window), min(length - 1, guess + window)
        cuts.append(min(range(lo, hi + 1), key=lambda p: line_score(img, axis, p)))
    return cuts


def trim(cell):
    """Shaves leftover gutter off the cell's edges."""
    w, h = cell.size
    def gutterish(box):
        return line_score_box(cell.crop(box)) < 40
    l, t, r, b = 0, 0, w, h
    while l < w // 6 and gutterish((l, 0, l + 1, h)):
        l += 1
    while r > w - w // 6 and gutterish((r - 1, 0, r, h)):
        r -= 1
    while t < h // 6 and gutterish((0, t, w, t + 1)):
        t += 1
    while b > h - h // 6 and gutterish((0, b - 1, w, b)):
        b -= 1
    return cell.crop((l, t, r, b))


def line_score_box(region):
    stat = ImageStat.Stat(region)
    return sum(abs(m - g) for m, g in zip(stat.mean, GUTTER)) + sum(stat.stddev) * 0.5


def square(cell):
    w, h = cell.size
    s = min(w, h)
    left, top = (w - s) // 2, (h - s) // 2
    return cell.crop((left, top, left + s, top + s)).resize((SIZE, SIZE), Image.LANCZOS)


def slice_grid(grid):
    src = ROOT / "art" / "grids" / f"{grid['id']}.png"
    if not src.exists():
        return 0
    img = Image.open(src).convert("RGB")
    xs, ys = boundaries(img, "x", COLS), boundaries(img, "y", ROWS)
    OUT.mkdir(parents=True, exist_ok=True)
    for i, (cell_id, _) in enumerate(grid["cells"]):
        r, c = divmod(i, COLS)
        cell = img.crop((xs[c] + 1, ys[r] + 1, xs[c + 1], ys[r + 1]))
        square(trim(cell)).save(OUT / f"{cell_id}.webp", "WEBP", quality=82, method=6)
    print(f"{grid['id']}: {len(grid['cells'])} cells -> public/art/")
    return len(grid["cells"])


def write_manifest():
    ids = sorted(p.stem for p in OUT.glob("*.webp")) if OUT.exists() else []
    body = ",\n".join(f"  '{i}'" for i in ids)
    (ROOT / "src" / "data" / "artManifest.ts").write_text(
        "// Generated by scripts/art/slice.py: ids that have a painted image in public/art/.\n"
        f"export const ART_IDS: ReadonlySet<string> = new Set([{chr(10) + body + ',' + chr(10) if ids else ''}]);\n"
    )
    print(f"artManifest.ts: {len(ids)} images")


def main():
    spec = json.loads((ROOT / "art" / "grids.json").read_text())
    wanted = set(sys.argv[1:])
    for grid in spec["grids"]:
        if not wanted or grid["id"] in wanted:
            slice_grid(grid)
    write_manifest()


if __name__ == "__main__":
    main()
